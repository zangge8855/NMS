export function getAuditEventLabel(eventType: unknown, locale = 'zh-CN'): string {
    const normalizedLocale = locale === 'en-US' ? 'en-US' : 'zh-CN';
    const key = String(eventType || '').trim();
    if (!key) return '';
    const direct = AUDIT_EVENT_LABELS[normalizedLocale][key];
    if (direct) return direct;
    const xrayMatch = /^xray_([a-z0-9_-]+)_(updated|update_failed)$/i.exec(key);
    if (xrayMatch) {
        const section = xrayMatch[1];
        const failed = xrayMatch[2].toLowerCase() === 'update_failed';
        return normalizedLocale === 'en-US'
            ? `Xray ${section} ${failed ? 'Update Failed' : 'Updated'}`
            : `更新 Xray ${section} ${failed ? '失败' : '成功'}`;
    }
    return '';
}
