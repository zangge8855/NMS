test('inbound list converts s-ui inbounds and clients into 3x-ui inbounds', async () => {
    await resetPanel();
    const server = addServer();
    const client = await ensureAuthenticated(server.id);
    // Save once so the fake panel generates local links.
    await compat.postUpdateClientCompat(client, 1, UUID_A, { email: 'alice', enable: true }, { email: 'alice' });

    const res = await client.get('/panel/api/inbounds/list');
    const inbounds = res.data.obj;
    const vless = inbounds.find((item) => item.id === 1);
    assert.equal(vless.protocol, 'vless');
    assert.equal(vless.remark, 'vless-reality');
    assert.equal(vless.port, 443);
    assert.equal(vless.enable, true);
    assert.equal(JSON.parse(vless.streamSettings).security, 'reality');
    const vlessClients = JSON.parse(vless.settings).clients;
    assert.deepEqual(vlessClients.map((item) => item.email).sort(), ['alice', 'bob']);
    const alice = vlessClients.find((item) => item.email === 'alice');
    assert.equal(alice.id, UUID_A);
    assert.equal(alice.flow, 'xtls-rprx-vision');
    assert.equal(alice.totalGB, 10 * 1024 ** 3);
    assert.equal(alice.expiryTime, 1893456000 * 1000);
    assert.equal(alice.subId, 'alice');
    assert.equal(alice.comment, 'vip');
    assert.equal(alice.shareLinks.length, 1);
    assert.match(alice.shareLinks[0], /^vless:\/\//);
    const bob = vlessClients.find((item) => item.email === 'bob');
    assert.equal(bob.expiryTime, -30 * 86400000, 'delayed start is a negative duration');

    const hy2 = inbounds.find((item) => item.id === 2);
    const hy2Client = JSON.parse(hy2.settings).clients[0];
    assert.equal(hy2Client.password, 'pw-alice');
    assert.match(hy2Client.shareLinks[0], /^hysteria2:\/\/pw-alice@/);
    assert.equal(JSON.parse(hy2.streamSettings).network, 'udp');

    const ss = inbounds.find((item) => item.id === 3);
    const ssSettings = JSON.parse(ss.settings);
    assert.equal(ssSettings.method, '2022-blake3-aes-256-gcm');
    assert.equal(ssSettings.clients[0].password, SS32);

    const trojan = inbounds.find((item) => item.id === 4);
    assert.deepEqual(JSON.parse(trojan.settings).clients, []);
    assert.equal(JSON.parse(trojan.streamSettings).network, 'ws');

    // alice is attached to 3 inbounds; her usage is split, not tripled.
    const totalUp = inbounds.reduce((sum, item) => sum + item.up, 0);
    assert.equal(totalUp, 3000 + 100);
    assert.equal(vless.clientStats.find((item) => item.email === 'alice').lastOnline, 1800000000 * 1000);
});

