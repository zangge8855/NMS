test('subscriptions use the links s-ui generated, filtered by policy', async () => {
    await resetPanel();
    const server = addServer();
    const client = await ensureAuthenticated(server.id);
    // Saving through the panel makes it generate local links for every attached inbound.
    await compat.postUpdateClientCompat(client, 1, UUID_A, { email: 'alice', enable: true }, { email: 'alice' });
    const { collectByServer } = await import('../routes/subscriptions.js');
    const meta = serverStore.getAll().find((item) => item.id === server.id);

    const all = await collectByServer(meta, 'alice', 'auto', { policy: {} });
    assert.equal(all.links.length, 3);
    assert.ok(all.links.some((link) => link.startsWith('vless://') && link.endsWith('#vless-reality')));
    assert.ok(all.links.some((link) => link.startsWith('hysteria2://') && link.endsWith('#hy2')));
    assert.ok(all.links.some((link) => link.startsWith('ss://')));
    assert.equal(all.perServer.nativeLinks, 3);
    assert.equal(all.perServer.reconstructedLinks, 0);
    assert.equal(all.skipped.length, 0);

    const hy2Only = await collectByServer(meta, 'alice', 'auto', {
        policy: { protocolScopeMode: 'selected', allowedProtocols: ['hysteria2'] },
    });
    assert.deepEqual(hy2Only.links.map((link) => link.split('://')[0]), ['hysteria2']);
});
