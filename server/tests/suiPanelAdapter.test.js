function addServer(overrides = {}) {
    return serverStore.add({
        name: `sui-${Math.random().toString(16).slice(2, 8)}`,
        url: panel.url,
        basePath: panel.basePath,
        panelType: 's-ui',
        username: 'admin',
        password: 'secret',
        ...overrides,
    });
}

