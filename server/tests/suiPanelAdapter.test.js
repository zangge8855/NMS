    assert.equal(config.shadowsocks.password, SS32, 'invalid ss key is not applied');

    const created = createSuiClientFromXui({ email: 'dave', expiryTime: -7 * 86400000 }, [1]);
    assert.equal(created.delayStart, true);
    assert.equal(created.resetDays, 7);
    assert.equal(created.expiry, 0);
    assert.deepEqual(created.links, []);

    const native = xuiInboundPayloadToSui({ suiInbound: { type: 'tuic', tag: 't', listen_port: 1, users: ['x'] } }, { id: 9, type: 'tuic', tag: 'old' });
    assert.equal(native.id, 9);
    assert.equal(native.tag, 't');
