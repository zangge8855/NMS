test('updating a client rotates credentials and keeps usage counters', async () => {
    await resetPanel();
    const server = addServer();
    const client = await ensureAuthenticated(server.id);
    panel.state.clients[0].up = 3000;
    await compat.postUpdateClientCompat(client, 1, UUID_A, {
        email: 'alice',
        id: UUID_B.replace(/2/g, '4'),
        flow: '',
        totalGB: 1024,
        expiryTime: 0,
        enable: false,
        reset: 30,
    }, { email: 'alice' });
    const alice = panel.state.clients.find((item) => item.name === 'alice');
    assert.equal(alice.config.vless.uuid, UUID_B.replace(/2/g, '4'));
    assert.equal(alice.config.tuic.uuid, UUID_B.replace(/2/g, '4'));
    assert.equal(alice.config.vless.flow, 'xtls-rprx-vision', 'empty flow does not strip vision');
    assert.equal(alice.config.trojan.password, 'pw-alice', 'password untouched');
    assert.equal(alice.volume, 1024);
    assert.equal(alice.expiry, 0);
    assert.equal(alice.enable, false);
    assert.equal(alice.autoReset, true);
    assert.equal(alice.resetDays, 30);
    assert.ok(alice.nextReset > Date.now() / 1000);
    assert.equal(alice.up, 3000, 'usage is not reset by an edit');
    assert.equal(alice.createdAt, 1700000000);
    assert.ok(alice.links.some((link) => link.type === 'external'), 'external links are kept');

    // Sending back the current password of one protocol is not a rotation.
    await compat.postUpdateClientCompat(client, 2, 'pw-alice', { email: 'alice', password: 'pw-alice' }, { email: 'alice' });
    assert.equal(panel.state.clients.find((item) => item.name === 'alice').config.shadowsocks.password, SS32);
});

